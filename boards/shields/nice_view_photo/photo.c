// 上游的 peripheral_status.c 會在 balloon 與 mountain 之間隨機挑一張；兩個都指向同一
// 份資料，隨機因此沒有作用。這樣不必為了改兩行而複製整個 peripheral_status.c。
#define PHOTO_DSC                                                                                  \
    {                                                                                              \
        .header.cf = LV_IMG_CF_INDEXED_1BIT, .header.always_zero = 0, .header.reserved = 0,        \
        .header.w = 140, .header.h = 68, .data_size = sizeof(photo_map), .data = photo_map,        \
    }

const lv_img_dsc_t balloon = PHOTO_DSC;
const lv_img_dsc_t mountain = PHOTO_DSC;

static struct zmk_widget_status status_widget;

lv_obj_t *zmk_display_status_screen() {

    lv_obj_t *screen;
    screen = lv_obj_create(NULL);

    zmk_widget_status_init(&status_widget, screen);
    lv_obj_align(zmk_widget_status_obj(&status_widget), LV_ALIGN_TOP_LEFT, 0, 0);

    return screen;
}
